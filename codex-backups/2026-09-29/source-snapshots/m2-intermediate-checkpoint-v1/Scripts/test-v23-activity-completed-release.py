"""Check the exact completed-report app release; optionally regenerate reviewed pins.

Default checks do not write repository files. --output writes a report only after
success. --materialize regenerates the three resources and the marked Swift/test
pin sections after all input, compiler, validator and candidate checks pass.
Rebind the explicit source pins/counts here only with the corresponding reviewed
wire/catalog change. --self-test exercises this real CLI in an isolated normal
repository-layout fixture, including read-only and failed-command guarantees.
"""
